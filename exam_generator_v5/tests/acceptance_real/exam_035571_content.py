def tangent_meet(t1, t2):
    """Intersection of the tangents to the unit circle at angles t1, t2 (radians)."""
    m = (t1 + t2) / 2
    r = 1 / math.cos((t2 - t1) / 2)
    return (round(r * math.cos(m), 6), round(r * math.sin(m), 6))


